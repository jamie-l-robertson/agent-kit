#!/usr/bin/env node
/**
 * Inventory kit vs project-owned skills; update AGENTS.md Skills line and
 * `.agents/memory/skills-inventory.md`. Non-destructive (never deletes skill dirs).
 *
 *   node scripts/sync-project-skills.mjs
 *   node scripts/sync-project-skills.mjs --check
 */

import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  statSync,
  writeFileSync,
} from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseFrontmatter } from './sync-tool-adapters.mjs'
import { KNOWN_KIT_SKILL_NAMES as KIT_SKILLS } from './kit-skill-names.mjs'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, '..')

const SKILL_ROOTS = [
  '.agents/skills',
  '.cursor/skills',
  '.claude/skills',
  '.github/skills',
]

export const KNOWN_KIT_SKILL_NAMES = KIT_SKILLS

const INVENTORY_PATH = join(ROOT, '.agents', 'memory', 'skills-inventory.md')
const AGENTS_MD = join(ROOT, 'AGENTS.md')

function read(p) {
  return readFileSync(p, 'utf8')
}

function listDirs(abs) {
  if (!existsSync(abs)) return []
  return readdirSync(abs).filter((n) => {
    try {
      return statSync(join(abs, n)).isDirectory()
    } catch {
      return false
    }
  })
}

export function listCanonicalKitSkillNames(root = ROOT) {
  const dir = join(root, '.agents', 'skills')
  const names = listDirs(dir)
  for (const n of names) KNOWN_KIT_SKILL_NAMES.add(n)
  return new Set(names)
}

/**
 * @typedef {{ name: string, path: string, description: string, owner: 'kit' | 'project' }} SkillEntry
 */

/**
 * @param {string} [root]
 * @returns {SkillEntry[]}
 */
export function scanSkills(root = ROOT) {
  const kitNames = listCanonicalKitSkillNames(root)
  /** @type {Map<string, SkillEntry>} */
  const byName = new Map()

  const rootOrder = new Map(SKILL_ROOTS.map((r, i) => [r, i]))

  for (const relRoot of SKILL_ROOTS) {
    const absRoot = join(root, relRoot)
    for (const name of listDirs(absRoot)) {
      const skillMd = join(absRoot, name, 'SKILL.md')
      if (!existsSync(skillMd)) continue
      const { frontmatter } = parseFrontmatter(read(skillMd))
      const skillName = String(frontmatter.name || name).trim() || name
      const description = String(frontmatter.description || '')
        .replace(/\s+/g, ' ')
        .trim()
      const owner =
        kitNames.has(name) ||
        kitNames.has(skillName) ||
        KNOWN_KIT_SKILL_NAMES.has(name) ||
        KNOWN_KIT_SKILL_NAMES.has(skillName)
          ? 'kit'
          : 'project'
      const pathRel = relative(root, join(absRoot, name)).split('\\').join('/')
      const next = { name: skillName, path: pathRel, description, owner }
      const prev = byName.get(skillName)
      if (!prev) {
        byName.set(skillName, next)
        continue
      }
      // Prefer earlier roots (.agents/skills first); keep kit owner if either is kit
      const prevRoot = prev.path.split('/').slice(0, 2).join('/')
      const nextRoot = pathRel.split('/').slice(0, 2).join('/')
      const preferNext =
        (rootOrder.get(nextRoot) ?? 99) < (rootOrder.get(prevRoot) ?? 99)
      const merged = preferNext ? next : prev
      if (prev.owner === 'kit' || next.owner === 'kit') merged.owner = 'kit'
      byName.set(skillName, merged)
    }
  }

  return [...byName.values()].sort((a, b) => a.name.localeCompare(b.name))
}

/** @param {SkillEntry[]} skills */
export function renderInventory(skills) {
  const kit = skills.filter((s) => s.owner === 'kit')
  const project = skills.filter((s) => s.owner === 'project')
  const lines = [
    '# Skills inventory',
    '',
    'Generated by `node scripts/sync-project-skills.mjs`. Do not hand-edit; re-run the script.',
    '',
    `## Kit (${kit.length})`,
    '',
  ]
  if (kit.length === 0) {
    lines.push('_none_', '')
  } else {
    lines.push('| Name | Path | Description |', '|------|------|-------------|')
    for (const s of kit) {
      lines.push(
        `| \`${s.name}\` | \`${s.path}\` | ${s.description || '—'} |`,
      )
    }
    lines.push('')
  }
  lines.push(`## Project (${project.length})`, '')
  if (project.length === 0) {
    lines.push('_none_', '')
  } else {
    lines.push('| Name | Path | Description |', '|------|------|-------------|')
    for (const s of project) {
      lines.push(
        `| \`${s.name}\` | \`${s.path}\` | ${s.description || '—'} |`,
      )
    }
    lines.push('')
  }
  return lines.join('\n')
}

/** @param {SkillEntry[]} skills */
export function renderAgentsSkillsLine(skills) {
  const kit = skills.filter((s) => s.owner === 'kit').map((s) => s.name)
  const project = skills.filter((s) => s.owner === 'project').map((s) => s.name)
  const kitList = kit.length
    ? kit.map((n) => `\`${n}\``).join(', ')
    : 'none'
  const projectList = project.length
    ? project.map((n) => `\`${n}\``).join(', ')
    : 'none'
  return `- **Skills**: kit — ${kitList}; project — ${projectList}. Inventory: \`.agents/memory/skills-inventory.md\`. Agent bodies compose \`.agents/protocols/\` at sync.`
}

/** @param {string} agentsMd @param {string} skillsLine */
export function patchAgentsSkillsLine(agentsMd, skillsLine) {
  if (/^- \*\*Skills\*\*:/m.test(agentsMd)) {
    return agentsMd.replace(/^- \*\*Skills\*\*:.*$/m, skillsLine)
  }
  // Insert under Stack when kept project AGENTS.md lacks a Skills line
  if (/^## Stack\s*$/m.test(agentsMd)) {
    return agentsMd.replace(/^## Stack\s*$/m, `## Stack\n\n${skillsLine}`)
  }
  return `${skillsLine}\n\n${agentsMd}`
}

export function buildOutputs(root = ROOT) {
  const skills = scanSkills(root)
  return {
    skills,
    inventory: renderInventory(skills),
    skillsLine: renderAgentsSkillsLine(skills),
  }
}

function writeInventory(content) {
  mkdirSync(dirname(INVENTORY_PATH), { recursive: true })
  writeFileSync(INVENTORY_PATH, content.endsWith('\n') ? content : `${content}\n`)
}

function main() {
  const check = process.argv.includes('--check')
  const { skills, inventory, skillsLine } = buildOutputs(ROOT)
  const kitCount = skills.filter((s) => s.owner === 'kit').length
  const projectCount = skills.filter((s) => s.owner === 'project').length

  if (check) {
    const mismatches = []
    if (!existsSync(INVENTORY_PATH)) {
      mismatches.push('missing .agents/memory/skills-inventory.md')
    } else if (read(INVENTORY_PATH) !== (inventory.endsWith('\n') ? inventory : `${inventory}\n`)) {
      mismatches.push('drift .agents/memory/skills-inventory.md')
    }
    if (!existsSync(AGENTS_MD)) {
      mismatches.push('missing AGENTS.md')
    } else {
      const md = read(AGENTS_MD)
      const line = md.split('\n').find((l) => l.startsWith('- **Skills**:'))
      if (!line) mismatches.push('AGENTS.md missing Skills line')
      else if (line !== skillsLine) mismatches.push('drift AGENTS.md Skills line')
    }
    if (mismatches.length) {
      console.error('Project skills inventory drift:')
      for (const m of mismatches) console.error(`  - ${m}`)
      process.exit(1)
    }
    console.log(
      `Skills inventory check OK (kit=${kitCount}, project=${projectCount})`,
    )
    return
  }

  writeInventory(inventory)
  if (!existsSync(AGENTS_MD)) {
    throw new Error('AGENTS.md not found')
  }
  const next = patchAgentsSkillsLine(read(AGENTS_MD), skillsLine)
  writeFileSync(AGENTS_MD, next.endsWith('\n') ? next : `${next}\n`)
  console.log(
    `Synced project skills inventory (kit=${kitCount}, project=${projectCount}) → AGENTS.md + .agents/memory/skills-inventory.md`,
  )
}

const isMain =
  process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]

if (isMain) {
  main()
}
